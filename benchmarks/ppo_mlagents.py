"""ML-Agents PPO path for the benchmark (config generator, no Unity connection).

Generates a YAML with IDENTICAL PPO hyperparameters per behavior from
benchmarks/ppo_common.yaml and prints the mlagents-learn command. This keeps
the ML-Agents side exactly in sync with the sb3/cleanrl/rllib hyperparams
without hand-editing YAMLs.

Caveat (documented in README + ppo_common.yaml): ML-Agents trains one policy
PER behavior with the same hyperparams (no cross-behavior weight sharing),
while sb3/cleanrl runners share a single policy across behaviors.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def generate_yaml(common, behaviors, out_path, max_steps_per_behavior=None):
    c = common["common"]
    m = common.get("mlagents", {}) or {}
    net = m.get("network", {}) or {}
    rs = m.get("reward_signals", {}) or {"extrinsic": {"gamma": c["gamma"], "strength": 1.0}}

    lines = ["# AUTO-GENERATED by benchmarks/ppo_mlagents.py — do not hand-edit.",
             "# Source: benchmarks/ppo_common.yaml (same nominal PPO hyperparams).",
             "behaviors:"]
    for b in behaviors:
        lines += [
            f"  {b}:",
            "    trainer_type: ppo",
            "    hyperparameters:",
            f"      batch_size: {c['minibatch_size']}",
            f"      buffer_size: {m.get('buffer_size', 6144)}",
            f"      learning_rate: {c['learning_rate']}",
            # Fairness: constant LR like SB3/RLlib/CleanRL-constant (NOT linear decay).
            "      learning_rate_schedule: constant",
            f"      beta: {c['ent_coef']}",
            f"      epsilon: {c['clip_range']}",
            f"      lambd: {c['gae_lambda']}",
            f"      num_epoch: {c['n_epochs']}",
            "    network_settings:",
            f"      normalize: {str(net.get('normalize', True)).lower()}",
            f"      hidden_units: {net.get('hidden_units', 256)}",
            f"      num_layers: {net.get('num_layers', 2)}",
            "    reward_signals:",
            "      extrinsic:",
            f"        gamma: {(rs.get('extrinsic', {}) or {}).get('gamma', c['gamma'])}",
            f"        strength: {(rs.get('extrinsic', {}) or {}).get('strength', 1.0)}",
            f"    max_steps: {max_steps_per_behavior or m.get('max_steps', 1000000)}",
            # Robustness: checkpoint every 100k (default 500k). A crash between
            # checkpoints loses at most 100k steps and --resume needs checkpoint.pt.
            f"    checkpoint_interval: {m.get('checkpoint_interval', 100000)}",
            f"    time_horizon: {m.get('time_horizon', 128)}",
            f"    summary_freq: {m.get('summary_freq', 2000)}",
            f"    threaded: {str(m.get('threaded', True)).lower()}",
            "",
        ]
    lines += ["engine_settings:",
              "  width: 1280", "  height: 720", "  quality_level: 2",
              f"  time_scale: {common['env'].get('time_scale', 3.0)}",
              "  target_frame_rate: -1", "  capture_frame_rate: 60", "  no_graphics: false", ""]
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return out_path


def default_behaviors():
    # Must match CompetitiveParkourEnvironment.cs behaviorNames.
    return ["MarioParkourPPO", "MarioParkourSAC", "MarioParkourDQN"]


def run(common, out_dir, run_id, behaviors=None, max_steps_per_behavior=None,
        base_port=5035, env_path=None, no_graphics=True, seed=0,
        python_exe=r"venv_mlagents\Scripts\python.exe"):
    behaviors = behaviors or default_behaviors()
    out_path = os.path.join(out_dir, f"{run_id}_ppo_mlagents.yaml")
    generate_yaml(common, behaviors, out_path, max_steps_per_behavior)
    # NOTE: invoked as `python -m ...` (not the mlagents-learn.exe wrapper:
    # setuptools entry-point launchers exit silently in this venv).
    cmd = (f"{python_exe} -m mlagents.trainers.learn {out_path} "
           f"--run-id {run_id}_mlagents --seed {seed} "
           f"--base-port {base_port} --force")
    if env_path:
        cmd += f" --env {env_path}" + (" --no-graphics" if no_graphics else "")
    print(f"[mlagents] YAML written to: {out_path}")
    print(f"[mlagents] max_steps/behavior={max_steps_per_behavior} "
          f"(x{len(behaviors)} behaviors = {max_steps_per_behavior * len(behaviors)} transitions)")
    print(f"[mlagents] Run:")
    print(f"  {cmd}")
    print("[mlagents] NOTE: 3 separate PPO policies (same hyperparams), vs 1 shared policy in sb3/cleanrl/rllib.")
    return out_path, cmd
